#!/usr/bin/env python3
"""Generate CFFI declarations and constants from the pinned raygui header.

Only raygui's simple public declarations are accepted; unknown C types fail.
Run from any directory. No third-party Python packages are needed.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
HEADER = (ROOT / "vendor/raygui.h").read_text()


def lisp_name(name):
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1-\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", name).replace("_", "-").lower()


def foreign_type(ctype):
    ctype = " ".join(ctype.split())
    if ctype == "const char *":
        return "nullable-string"
    if "*" in ctype:
        return ":pointer"
    return {"void": ":void", "int": ":int", "bool": "c-bool",
            "float": ":float", "Font": "(:struct cl-raylib::%font)",
            "Color": "(:struct cl-raylib::%color)",
            "Rectangle": "(:struct cl-raylib::%rectangle)"}[ctype]


def generate():
    constants = []
    enums = []
    clean = re.sub(r"/\*.*?\*/|//[^\n]*", "", HEADER, flags=re.S)
    for body, enum_name in re.findall(r"typedef\s+enum\s*\{([^}]+)\}\s*(Gui\w+)\s*;", clean):
        value = -1
        entries = []
        for entry in body.split(","):
            if not entry.strip():
                continue
            match = re.fullmatch(r"\s*(\w+)\s*(?:=\s*(\d+))?\s*", entry)
            if not match:
                raise ValueError(entry)
            cname, explicit = match.groups()
            value = int(explicit) if explicit is not None else value + 1
            name = lisp_name(cname)
            constants.append((f"+{name}+", value))
            entries.append(f"  (:{name} {value})")
        enums.append((lisp_name(enum_name), entries))
    constants += [("+scrollbar-left-side+", 0), ("+scrollbar-right-side+", 1)]
    functions = []
    declarations = []
    for result, cname, args in re.findall(r"^RAYGUIAPI\s+(.+?)\s*(Gui\w+)\(([^)]*)\);", HEADER, re.M):
        name = lisp_name(cname)
        functions.append(name)
        # IconText returns a borrowed string; CFFI copies it immediately.
        returns = "(:string :encoding :utf-8)" if result.strip() == "const char *" else foreign_type(result)
        params = []
        for arg in args.split(","):
            if arg.strip() == "void":
                continue
            match = re.fullmatch(r"\s*(.+?[\s*])(\w+)\s*", arg)
            ctype, argname = match.groups()
            # Tooltip strings are retained by C. Never translate a temporary.
            argtype = ":pointer" if cname == "GuiSetTooltip" else foreign_type(ctype)
            params.append(f"  ({lisp_name(argname)} {argtype})")
        declarations.append(f'(cffi:defcfun ("{cname}" {name}) {returns}' +
                            ("\n" + "\n".join(params) if params else "") + ")")
    prelude = ";;; Generated by tools/generate-bindings.py from raygui 5.0. Do not edit.\n"
    (ROOT / "src/bindings.lisp").write_text(prelude + "(in-package #:cl-raygui.raw)\n\n" + "\n\n".join(declarations) + "\n")
    enum_forms = [f"(cffi:defcenum {name}\n" + "\n".join(entries) + ")" for name, entries in enums]
    constant_forms = [f"(defconstant {name} {value})" for name, value in constants]
    (ROOT / "src/constants.lisp").write_text(prelude + "(in-package #:cl-raygui.raw)\n\n" + "\n\n".join(enum_forms) + "\n\n" + "\n".join(constant_forms) + "\n")
    # Functions replaced by the safe Lisp API must have distinct package symbols.
    wrapped = set("""gui-set-tooltip gui-set-alpha gui-set-style gui-get-style
        gui-button gui-label-button gui-window-box
        gui-toggle gui-toggle-group gui-toggle-slider gui-check-box gui-combo-box
        gui-dropdown-box gui-spinner gui-value-box gui-value-box-float gui-text-box
        gui-slider gui-slider-bar gui-progress-bar gui-grid gui-scroll-panel
        gui-list-view gui-list-view-ex gui-tab-bar gui-tab-bar-ex gui-message-box
        gui-text-input-box gui-color-picker gui-color-panel gui-color-bar-alpha
        gui-color-bar-hue gui-color-picker-hsv gui-color-panel-hsv""".split())
    extra = """result-pressed-p result-changed-p result-tab-close-p
        make-text-buffer free-text-buffer with-text-buffer text-buffer-string
        text-buffer-capacity text-buffer-pointer""".split()
    common = [n for n, _ in constants] + [n for n, _ in enums] + ["gui-style-prop", "control-id", "property-id", "property-value", "load-raygui"]
    raw_exports = functions + common
    imports = [n for n in raw_exports if n not in wrapped]
    symbols = lambda names: "\n".join("    #:" + n for n in names)
    package = (prelude + "(defpackage #:cl-raygui.raw\n  (:nicknames #:raygui.raw)\n  (:use #:cl)\n  (:export\n" + symbols(raw_exports) + "))\n\n" +
               "(defpackage #:cl-raygui\n  (:nicknames #:raygui)\n  (:use #:cl)\n  (:import-from #:cl-raygui.raw\n" + symbols(imports) + ")\n  (:export\n" + symbols(raw_exports + extra) + "))\n")
    (ROOT / "src/package.lisp").write_text(package)
    return len(functions), len(constants)


if __name__ == "__main__":
    functions, constants = generate()
    print(f"Generated {functions} functions and {constants} constants.")
